// ============================================================================
//  synthfont_faces.h - three alternative faces for synthfont.h, drawn to stay
//  readable further away. Same 6-unit grid, same renderer; what differs is the
//  drawing and the metric and shading constants.
//
//  The shipping face merges 11 of 22 confusable letter pairs by five feet
//  (O/0 and D/O go at one foot). These are scored on the distance at which a
//  pair stops being separable under a 20/20 acuity model on the panel's real
//  247 ppi, and on the worst five pairs rather than the mean, because a face is
//  only as legible as its most confusable pair.
//
//                  worst 5 pairs   merging under 5 ft
//    SYNTHFONT        1.0 ft          11 of 22
//    BOULEVARD        3.4 ft           4 of 22
//    BEACON           5.1 ft           3 of 22
//    MARQUEE          3.9 ft           3 of 22
//
//  Usage:
//      #include "synthfont.h"
//      #include "synthfont_faces.h"
//      synth::render(synth::BEACON, frame, distBuf, SCREEN_W, SCREEN_H, text);
//
//  Calling render() without a face still draws SYNTHFONT, unchanged.
// ============================================================================
